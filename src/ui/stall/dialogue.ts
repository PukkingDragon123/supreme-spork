// What shopkeepers say. Lines are picked by dialect (ภาษาเหนือ อีสาน ใต้,
// Thai-Chinese, 7-บุญ staff, teen) with a pinch of randomness.

import type { Dialect, StallNpc } from '../../game/stalls'
import type { PlaceShop } from '../../game/data/placeShops'

const pick = <T,>(a: readonly T[]): T => a[Math.floor(Math.random() * a.length)]

type Lines = Partial<Record<Dialect, string[]>> & { central: string[] }

function by(npc: StallNpc, l: Lines): string {
  const own = l[npc.dialect]
  const list = own && own.length ? own : l.central
  const politeM = npc.gender === 'm'
  // How the shopkeeper calls themself (ป้า / ลุง / พี่) and you (ลูก / หลาน / น้อง).
  const me = npc.elder ? (politeM ? 'ลุง' : 'ป้า') : 'พี่'
  const you = npc.elder ? (politeM ? 'หลาน' : 'ลูก') : 'น้อง'
  return pick(list)
    .replace(/\{k\}/g, politeM ? 'ครับ' : 'ค่ะ')
    .replace(/\{j\}/g, politeM ? 'ครับ' : 'จ้า')
    .replace(/\{me\}/g, me)
    .replace(/\{you\}/g, you)
}

function fill(t: string, v: Record<string, string>) {
  return t.replace(/\{(\w+)\}/g, (m, k) => v[k] ?? m)
}

const RARE_WORD: Record<string, string> = {
  common: 'ของขายดี',
  uncommon: 'ของสวยน่าสะสม',
  rare: 'ของหายากเลยนะ',
  epic: 'ของเด็ดสุดยอดประจำร้าน',
  legendary: 'ของระดับตำนาน นาน ๆ จะเข้าที',
}

export function recommendLine(npc: StallNpc, shop: PlaceShop, item: { name: string; rarity?: string; kind: string } | null): string {
  if (shop.lines?.recommend?.length && Math.random() < 0.4) return pick(shop.lines.recommend)
  if (!item)
    return by(npc, {
      central: ['วันนี้ของหมดเกลี้ยงแล้ว{j} พรุ่งนี้มาใหม่นะ', 'ของดีขายหมดตั้งแต่เช้าเลย{j} มาไวกว่านี้นะคราวหน้า'],
      north: ['ของหมดแล้วเจ้า ปรือนี้มาใหม่เน้อ'],
      isan: ['ของหมดแล้วเด้อ มื้ออื่นมาใหม่เด้อ'],
      south: ['ของหมดแล้วหนา พรุ่งนี้มาหลาว ๆ'],
      chinese: ['หมดแล้วลื้อ พรุ่งนี้มาใหม่ เฮงเฮง'],
      polite: ['ขออภัย{k} สินค้าหมดชั่วคราว{k}'],
    })
  const w = RARE_WORD[item.rarity ?? 'common'] ?? 'ของดี'
  const v = { n: item.name, w }
  if (item.kind === 'snack')
    return fill(
      by(npc, {
        central: ['ลอง {n} สิ{j} อร่อยจนต้องกลับมาซื้อซ้ำ', '{n} เลย{j} ทำใหม่ร้อน ๆ กินแล้วมีแรงทำบุญ', 'ขายดีสุดคือ {n}{j} {me}รับประกันความอร่อย'],
        north: ['กิ๋น {n} ก่อนเน้อ ลำขนาดเจ้า', '{n} ลำแต๊ ๆ เจ้า ลองแล้วจะติดใจ'],
        isan: ['{n} แซ่บหลายเด้อ ลองเบิ่งแน่', 'เอา {n} บ่ อร่อยคักเด้อ'],
        south: ['{n} หรอยจังฮู้ ลองดูหนา', 'กิน {n} แล้วจะหรอยไปทั้งวัน'],
        chinese: ['{n} นี่อร่อยที่สุด อั๊วทำเองกับมือ ลื้อต้องลอง', 'ลื้อกิน {n} ไป เฮงทั้งวัน'],
        polite: ['{n} ขายดีอันดับหนึ่ง{k} รับเพิ่มไหม{k}', 'โปรวันนี้{k} {n} อร่อยมาก{k}'],
        teen: ['{n} ปังมากค่ะ ของมันต้องกิน!', 'ลอง {n} ค่ะ อร่อยจนต้องรีวิว'],
      }),
      v,
    )
  return fill(
    by(npc, {
      central: ['{n} นี่เลย{j} {w}', 'ตัวนี้เลย {n} {w} ใครเห็นก็อยากได้', '{n} เข้ามาใหม่วันนี้{j} {w} หมดแล้วหมดเลยนะ'],
      north: ['{n} งามขนาดเจ้า {w}', 'เอา {n} ไปเน้อ {w} งามแต๊ ๆ'],
      isan: ['{n} งามหลายเด้อ {w}', 'สิเอา {n} บ่ {w}เด้อ'],
      south: ['{n} สวยจังฮู้ {w}หนา', 'แลนี่ {n} {w} ไม่มีที่ไหนแล้ว'],
      chinese: ['{n} นี่ของดี {w} อั๊วเก็บไว้ให้ลื้อคนเดียว', 'ลื้อดู {n} {w} ซื้อไปเฮงเฮง'],
      polite: ['{n} {w}{k} เป็นสินค้าแนะนำประจำสาขา{k}', 'แนะนำ {n}{k} {w}{k}'],
      teen: ['{n} ค่ะ {w} ตัวแม่ต้องมี!', 'ของมันต้องมีค่ะ {n} {w}'],
    }),
    v,
  )
}

