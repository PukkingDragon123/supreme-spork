interface Mat {
  l: string
  b: string
  s: string
  d: string
}

function mat(b: string, s?: string, l?: string): Mat {
  const sh = s ?? mix(b, INK, 0.22)
  return { l: l ?? mix(b, '#ffffff', 0.35), b, s: sh, d: mix(sh, INK, 0.5) }
}

