export const THAI_DIGITS = ['๐', '๑', '๒', '๓', '๔', '๕', '๖', '๗', '๘', '๙']
export const toThaiDigits = (n: number | string) =>
  String(n)
    .split('')
    .map((c) => (c >= '0' && c <= '9' ? THAI_DIGITS[+c] : c))
    .join('')
