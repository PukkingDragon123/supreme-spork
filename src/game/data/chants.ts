/** Pixel illustration drawn on a chant's meaning card (see src/art/chantArt.ts). */
export type ChantArt =
  | 'bow'
  | 'gems'
  | 'virtues'
  | 'dhamma'
  | 'sangha'
  | 'heart'
  | 'metta'
  | 'sila'
  | 'ganesha'
  | 'guanyin'
  | 'lakshmi'
  | 'jina'
  | 'bahum'
  | 'yatha'

/** Meaning of a group of lines [from, to). */
export interface ChantVerse {
  from: number
  to: number
  /** Simple Thai meaning of these lines. */
  text: string
  /** Which parts of the illustration light up for these lines. */
  focus?: number[]
  /** Illustration for this verse (defaults to the chant's). */
  art?: ChantArt
}

export interface Chant {
  id: string
  name: string
  short: string
  lines: string[]
  /** Whole-chant meaning in simple Thai. */
  meaning: string
  /** When Thai people chant it. */
  when: string
  art: ChantArt
  verses?: ChantVerse[]
  merit: number
  /** Minimum level to unlock. */
  level?: number
  repeat?: number
  /** Buddhist (default), Brahmin-Hindu or Chinese Mahayana. */
  faith?: 'buddhist' | 'hindu' | 'mahayana'
  /** Composite chants: the chants it strings together. */
  parts?: string[]
}

