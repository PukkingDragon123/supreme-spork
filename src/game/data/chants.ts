function buildSet(def: (typeof SETS)[number]): Chant {
  const parts = def.parts.map((id) => CHANTS.find((c) => c.id === id)!)
  const lines: string[] = []
  const verses: ChantVerse[] = []
  for (const p of parts) {
    const off = lines.length
    const vs = p.verses?.length ? p.verses : [{ from: 0, to: p.lines.length, text: p.meaning }]
    for (const v of vs) verses.push({ ...v, from: v.from + off, to: v.to + off, art: v.art ?? p.art })
    lines.push(...p.lines)
  }
  return {
    id: def.id,
    name: def.name,
    short: def.short,
    lines,
    meaning: parts.map((p) => p.meaning).join(' · '),
    when: def.when,
    art: parts[0].art,
    verses,
    merit: def.merit,
    parts: def.parts,
    faith: parts[0].faith,
  }
}

/** Composite chants used by boss stages (not listed as separate chants in the book). */
export const CHANT_SETS: Chant[] = SETS.map(buildSet)

const ALL = [...CHANTS, ...CHANT_SETS]
export const CHANT_BY_ID: Record<string, Chant> = Object.fromEntries(ALL.map((c) => [c.id, c]))

/** The verse (line group) a chant line belongs to. */
export function verseOf(c: Chant, line: number): ChantVerse | null {
  return c.verses?.find((v) => line >= v.from && line < v.to) ?? null
}

